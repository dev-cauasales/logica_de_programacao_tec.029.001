#entrada de dados
n1 = int(input("informe o primeiro numero: "))
n2 = int(input("Informe o segundo numero: "))

#saida de dados
soma = n1 + n2
subtracao = n1 - n2
multiplicacao = n1 * n2
divisao = n1 / n2 
resto = n1 % n2

print (f"Soma: {soma}")
print (f"Subtracao: {subtracao}")
print (f"Multiplicacao: {multiplicacao}")
print (f"Divisao: {divisao}")
print(f"Resto: {resto}")
